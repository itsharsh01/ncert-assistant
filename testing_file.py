def retrieve_and_rerank_chunks(query: str):
    """
    Retrieves and re-ranks chunks based on a given query using hybrid retrieval and a cross-encoder.
    Returns at most the top 3 chunks with positive scores.
    """
    # 1. Hybrid Retrieval (BM25 + Vector Store)
    final_docs = hybrid_retriever.invoke(query)

    # 2. Re-ranking with Cross-Encoder
    candidate_pairs = [(query, doc.page_content) for doc in final_docs]
    sim_scores = reranker_model.predict(candidate_pairs)
    scored_docs = sorted(zip(sim_scores, final_docs), key=lambda x: x[0], reverse=True)

    # 3. Filter for positive scores and take top 3
    filtered_docs = []
    for score, doc in scored_docs:
        if score > 0:
            filtered_docs.append((score, doc))
        if len(filtered_docs) >= 3:
            break

    return filtered_docs

