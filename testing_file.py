def parse_ncert_to_markdown(file_path: str) -> str:
    """
    Converts the NCERT PDF into clean Markdown using LlamaParse.
    This preserves the layout, tables, and structural headers.
    """
    print(f"Parsing {file_path} to Markdown...")
    parser = LlamaParse(
        result_type="markdown",  # Crucial for structural chunking
        verbose=True,
        language="en"
    )

    # Extract documents
    documents = parser.load_data(file_path)

    # Combine pages into a single markdown string
    full_markdown = "\n\n".join([doc.text for doc in documents])
    return full_markdown

def chunk_ncert_content(markdown_text: str):
    """
    Applies Structural Chunking followed by a Recursive Character Fallback.
    """
    # ---------------------------------------------------------
    # STEP 1: Structural Splitting (Document-Aware)
    # ---------------------------------------------------------
    # Define which Markdown headers we want to split on and what to name their metadata keys
    headers_to_split_on = [
        ("#", "Chapter"),
        ("##", "Main_Topic"),
        ("###", "Sub_Topic"),
        ('####', "Sub_Sub_Topic"),
        ("#####", "Sub_Sub_Sub_Topic")
    ]

    markdown_splitter = MarkdownHeaderTextSplitter(
        headers_to_split_on=headers_to_split_on,
        strip_headers=False # Keep the header in the chunk text for LLM context
    )

    # This creates chunks based purely on the semantic structure of the book
    structural_chunks = markdown_splitter.split_text(markdown_text)
    print(f"Generated {len(structural_chunks)} structural chunks.")

    # ---------------------------------------------------------
    # STEP 2: Recursive Fallback (Token/Character limitation)
    # ---------------------------------------------------------
    # If a section under a heading is massive, we break it down further.
    # Adjust chunk_size to match your embedding model's context window (e.g., 512 or 1024 tokens)
    recursive_splitter = RecursiveCharacterTextSplitter(
        chunk_size=1000,     # Characters (approx 200-250 tokens)
        chunk_overlap=150,   # Preserve context across splits
        separators=["\n\n", "\n", ". ", " ", ""] # Hierarchical splitting
    )

    final_chunks = recursive_splitter.split_documents(structural_chunks)

    return final_chunks

